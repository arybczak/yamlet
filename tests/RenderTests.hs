-- | A generated file with a header, and empty lines between the jobs and
-- between the steps. The header is on the root, so the file has no start
-- marker.
test_workflow :: Assertion
test_workflow = do
  let out = renderSyntax defaultRenderOptions [doc]
  assertEqual "output" expected out
  assertEqual
    "header read back"
    (Right [[Comment "Generated by haskell-gha.", Comment "Do not edit.", EmptyLine]])
    (map (\d -> d.root.comments.before) <$> parseDocumentsText out)
  where
    doc :: Document
    doc =
      Document
        { version = Nothing
        , explicitStart = False
        , explicitEnd = False
        , docComments = noComments
        , root =
            withHeader $
              mappingNode
                [ (plainNode "name", plainNode "CI")
                ,
                  ( withEmptyLine (plainNode "jobs")
                  , mappingNode
                      [
                        ( withEmptyLine (plainNode "build")
                        , mappingNode
                            [ (plainNode "runs-on", plainNode "ubuntu-latest")
                            ,
                              ( plainNode "steps"
                              , sequenceNode
                                  [ mappingNode [(plainNode "uses", plainNode "actions/checkout@v4")]
                                  , withEmptyLine $
                                      mappingNode
                                        [ (plainNode "name", plainNode "Build")
                                        , (plainNode "run", scalarNode Literal "cabal build\ncabal test\n")
                                        ]
                                  ]
                              )
                            ]
                        )
                      , (withEmptyLine (plainNode "lint"), mappingNode [(plainNode "ghc", scalarNode SingleQuoted "9.10")])
                      ]
                  )
                ]
        }

    withEmptyLine :: Node -> Node
    withEmptyLine n = n {comments = n.comments {before = [EmptyLine]}}

    withHeader :: Node -> Node
    withHeader n = n {comments = n.comments {before = [Comment "Generated by haskell-gha.\nDo not edit."]}}

    expected :: T.Text
    expected =
      T.unlines
        [ "# Generated by haskell-gha."
        , "# Do not edit."
        , ""
        , "name: CI"
        , ""
        , "jobs:"
        , ""
        , "  build:"
        , "    runs-on: ubuntu-latest"
        , "    steps:"
        , "    - uses: actions/checkout@v4"
        , ""
        , "    - name: Build"
        , "      run: |"
        , "        cabal build"
        , "        cabal test"
        , ""
        , "  lint:"
        , "    ghc: '9.10'"
        ]

