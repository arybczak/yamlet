-- | The text of a document with the node as its root.
render :: Node -> T.Text
render n = renderSyntax defaultRenderOptions [document n]

-- | Parsing and rendering gives back the input.
rendersBack :: String -> T.Text -> Assertion
rendersBack preface input = assertEqual preface (Right input) (renderSyntax defaultRenderOptions <$> parseDocumentsText input)

-- | Parsing and rendering gives the expected text, which gives itself back.
rendersAs :: String -> T.Text -> T.Text -> Assertion
rendersAs preface expected input = do
  assertEqual preface (Right expected) (renderSyntax defaultRenderOptions <$> parseDocumentsText input)
  rendersBack (preface ++ ", rendered again") expected

test_fallbacks :: Assertion
test_fallbacks = do
  assertEqual "plain with a colon" "'a: b'\n" (render (plainNode "a: b"))
  assertEqual "plain number stays plain" "12\n" (render (plainNode "12"))
  assertEqual "single-quoted line break" "\"a\\nb\"\n" (render (scalarNode SingleQuoted "a\nb"))
  assertEqual "literal with an indicator at the top level" "\" a\\nb\"\n" (render (scalarNode Literal " a\nb"))
  assertEqual "folded with an indicator at the top level" "\" a\\nb\"\n" (render (scalarNode Folded " a\nb"))
  let withLineBelow :: Node -> Node
      withLineBelow n = n {comments = noComments {after = [Comment "c"]}}
  assertEqual "empty literal with a line below at the top level" "\"\"\n# c\n" (render (withLineBelow (scalarNode Literal "")))
  assertEqual "empty folded with a line below at the top level" "\"\"\n# c\n" (render (withLineBelow (scalarNode Folded "")))
  assertEqual
    "literal of only line breaks with a line below at the top level"
    (Right [(ScalarContent DoubleQuoted "\n", [("", "after", "c")])])
    ( map (\d -> (d.root.content, commentsOf d))
        <$> parseDocumentsText (render (withLineBelow (scalarNode Literal "\n")))
    )
  assertEqual "literal with a line below in a list" "- |-\n# c\n" (render (sequenceNode [withLineBelow (scalarNode Literal "")]))
  assertEqual "literal with an indicator in a list" "- |2-\n   a\n  b\n" (render (sequenceNode [scalarNode Literal " a\nb"]))
  assertEqual "folded with a tab in a list" "- >2-\n  \ta\n  b\n" (render (sequenceNode [scalarNode Folded "\ta\nb"]))
  -- A block scalar cannot hold the character, so the lines below it stay
  -- deeper than the key, as below any quoted scalar.
  let quotedBlocks =
        mappingNode
          [ (plainNode "a", withLineBelow (scalarNode Literal "x\DEL"))
          , (plainNode "b", sequenceNode [withLineBelow (scalarNode Folded "x\DEL"), plainNode "y"])
          , (sequenceNode [plainNode "k"], withLineBelow (scalarNode Literal "x\DEL"))
          ]
  assertEqual
    "lines below a block scalar in double quotes"
    "a: \"x\\x7F\"\n  # c\nb:\n- \"x\\x7F\"\n  # c\n- y\n? - k\n: \"x\\x7F\"\n  # c\n"
    (render quotedBlocks)
  assertEqual
    "lines below a block scalar in double quotes read back"
    (Right [[("/a", "after", "c"), ("/b/0", "after", "c"), ("/?", "after", "c")]])
    (map commentsOf <$> parseDocumentsText (render quotedBlocks))
  assertEqual
    "keep indicator"
    "- |+\n  a\n\n- b\n"
    (render (sequenceNode [scalarNode Literal "a\n\n", (plainNode "b") {comments = noComments {before = [EmptyLine]}}]))
  assertEqual
    "block scalar in a flow collection"
    "[\"a\\n\"]\n"
    (render (contentNode (SequenceContent Flow [scalarNode Literal "a\n"])))
  -- YAML 1.1 parsers read a comma or a bracket right after a tag as part of
  -- the tag.
  assertEqual
    "empty item of a flow sequence"
    "[!!null , a, !!null ]\n"
    (render (contentNode (SequenceContent Flow [plainNode "", plainNode "a", plainNode ""])))
  assertEqual
    "empty tagged values in flow collections"
    (Right "[80, !!str , 443]\n---\n{a: !!str , b: !!str }\n")
    (renderSyntax defaultRenderOptions <$> parseDocumentsText "[80, !!str , 443]\n---\n{a: !!str , b: !!str }\n")
  -- YAML 1.1 parsers misread or reject these plain scalars, empty keys and
  -- empty values in flow collections.
  assertEqual
    "indicators in plain scalars of a flow collection"
    "['?a', 'a?b', ':a', 'a:?', a:b, -a]\n"
    (render (contentNode (SequenceContent Flow (map plainNode ["?a", "a?b", ":a", "a:?", "a:b", "-a"]))))
  rendersAs
    "empty keys and values in flow mappings"
    "{k: , a: 1}\n---\n{? : x}\n---\n{? }\n"
    "{k:, a: 1}\n---\n{: x}\n---\n{: }\n"
  -- libyaml and PyYAML reject an implicit key of more than 1024 characters
  -- in a flow mapping too.
  let flowEntry :: Node -> Node -> Node
      flowEntry k v = contentNode (MappingContent Flow [(k, v)])
      longest = T.replicate 1024 "a"
      long = T.replicate 1025 "a"
      anchoredKey = (plainNode (T.replicate 1020 "a")) {props = noProps {anchor = Just "anchor"}}
  assertEqual "flow key of the longest length" ("{" <> longest <> ": 1}\n") (render (flowEntry (plainNode longest) (plainNode "1")))
  assertEqual "long flow key" ("{? " <> long <> " : 1}\n") (render (flowEntry (plainNode long) (plainNode "1")))
  assertEqual "long flow key without a value" ("{? " <> long <> "}\n") (render (flowEntry (plainNode long) (plainNode "")))
  assertEqual
    "flow key that an anchor makes long"
    ("{? &anchor " <> T.replicate 1020 "a" <> " : 1}\n")
    (render (flowEntry anchoredKey (plainNode "1")))
  let longTag = "!" <> T.replicate 1100 "t"
      longTagged = (plainNode "") {props = noProps {tag = Tag longTag}}
  assertEqual
    "flow key that a tag makes long, without a value"
    ("{? " <> longTag <> " , b: c}\n")
    (render (contentNode (MappingContent Flow [(longTagged, plainNode ""), (plainNode "b", plainNode "c")])))
  assertEqual
    "long flow keys read back"
    (Right [Mapping [(String long, Int 1)], Mapping [(String long, Null)], Mapping [(String (T.replicate 1020 "a"), Int 1)]])
    ( decodeAllText @Value . renderSyntax defaultRenderOptions $
        map
          document
          [flowEntry (plainNode long) (plainNode "1"), flowEntry (plainNode long) (plainNode ""), flowEntry anchoredKey (plainNode "1")]
    )
  assertEqual "empty key" "?\n: a\n" (render (mappingNode [(plainNode "", plainNode "a")]))
  let emptyWithComment = (contentNode (SequenceContent Block [])) {comments = noComments {after = [Comment "c"]}}
      commented = mappingNode [(plainNode "k", emptyWithComment)]
  assertEqual "comment in an empty collection" "k: [\n  # c\n  ]\n" (render commented)
  assertEqual
    "comment in an empty collection reads back"
    (Right [[("/k", "after", "c")]])
    (map commentsOf <$> parseDocumentsText (render commented))
  let keyWithLineBelow :: Node -> Node
      keyWithLineBelow v = mappingNode [((plainNode "k") {comments = noComments {after = [Comment "c"]}}, v), (plainNode "l", plainNode "y")]
      flowSequence :: Node
      flowSequence = contentNode (SequenceContent Flow [plainNode "a"])
  assertEqual "lines after a key with a flow value" "# c\nk: [a]\nl: y\n" (render (keyWithLineBelow flowSequence))
  assertEqual
    "lines after a key with a flow value read back"
    (Right [[("/k:key", "before", "c")]])
    (map commentsOf <$> parseDocumentsText (render (keyWithLineBelow flowSequence)))
  assertEqual
    "lines after a key with an empty flow value"
    "# c\nk: {}\nl: y\n"
    (render (keyWithLineBelow (contentNode (MappingContent Flow []))))
  assertEqual
    "comment in an empty key"
    "? [\n  # c\n  ]\n: v\n"
    (render (mappingNode [(emptyWithComment, plainNode "v")]))
  assertEqual
    "comment in an empty key reads back"
    (Right [[("/?:key", "after", "c")]])
    (map commentsOf <$> parseDocumentsText (render (mappingNode [(emptyWithComment, plainNode "v")])))
  assertEqual
    "white space at the end of a comment"
    "# y\na # x\n"
    (render (plainNode "a") {comments = noComments {before = [Comment "y\t"], inline = Just "x "}})
  let anchored :: T.Text -> Node -> Node
      anchored a n = n {props = noProps {anchor = Just a}}
  assertEqual
    "invalid anchor names"
    "[&a_b x, *a_b, &a_b_2 y, *a_b_2, &anchor z, *anchor]\n"
    ( render . contentNode $
        SequenceContent
          Flow
          [ anchored "a b" (plainNode "x")
          , contentNode (AliasContent "a b")
          , anchored "a]b" (plainNode "y")
          , contentNode (AliasContent "a]b")
          , anchored "" (plainNode "z")
          , contentNode (AliasContent "")
          ]
    )
  let tagged :: T.Text -> Node
      tagged t = (plainNode "x") {props = noProps {tag = Tag t}}
      tagOf :: T.Text -> Either String [Tag]
      tagOf t = case parseDocumentsText (render (tagged t)) of
        Right docs -> Right [d.root.props.tag | d <- docs]
        Left err -> Left (show err)
  assertEqual "empty tag" "! x\n" (render (tagged ""))
  assertEqual "global tag" "!<tag:example.com,2000:x> x\n" (render (tagged "tag:example.com,2000:x"))
  assertEqual "tag with a directive" "%TAG !t74! %74\n---\n!t74!ag:x%3Ey x\n" (render (tagged "tag:x>y"))
  mapM_
    (\t -> assertEqual ("tag " ++ show t) (Right [Tag t]) (tagOf t))
    ["tag:x>y", "x%2", "foo", "#a b", "!a b", "tag:x%41", "tag:yaml.org,2002:a%", "\x100\&z"]
  assertEqual
    "directives after a document"
    (Right [(NoTag, ScalarContent Plain "a"), (Tag "foo", ScalarContent Plain "x")])
    ( map (\d -> (d.root.props.tag, d.root.content))
        <$> parseDocumentsText (renderSyntax defaultRenderOptions [document (plainNode "a"), document (tagged "foo")])
    )
  assertEqual
    "taken anchor name"
    "- &a_b x\n- &a_b_2 y\n- *a_b_2\n"
    (render (sequenceNode [anchored "a_b" (plainNode "x"), anchored "a b" (plainNode "y"), contentNode (AliasContent "a b")]))
  assertEqual
    "anchor names with line separators"
    "- &a_b x\n- &c_d y\n- *a_b\n- *c_d\n"
    ( render
        ( sequenceNode
            [ anchored "a\x2028\&b" (plainNode "x")
            , anchored "c\x2029\&d" (plainNode "y")
            , contentNode (AliasContent "a\x2028\&b")
            , contentNode (AliasContent "c\x2029\&d")
            ]
        )
    )

-- | The new names of many invalid anchor names with one base take linear
-- time, not quadratic.
test_manyAnchors :: Assertion
test_manyAnchors = do
  let names = map T.pack (mapM (const " ,[]{}") [1 .. 6 :: Int])
      tree = sequenceNode [(plainNode "x") {props = noProps {anchor = Just a}} | a <- names]
  assertEqual
    "first and last names"
    ["- &______ x", "- &_______" <> T.pack (show (length names)) <> " x"]
    ( case T.lines (render tree) of
        first : rest -> first : take 1 (reverse rest)
        [] -> []
    )

-- | The time to render nested flow collections with a comment inside is
-- linear in the depth.
test_deepComment :: Assertion
test_deepComment =
  assertEqual
    "output"
    (Right (T.replicate (depth - 1) "- " <> "[\n" <> indent <> "# c\n" <> indent <> "]\n"))
    (renderSyntax defaultRenderOptions <$> parseDocumentsText (T.replicate depth "[" <> " # c\n" <> T.replicate depth "]\n"))
  where
    depth :: Int
    depth = 100000

    indent :: T.Text
    indent = T.replicate (2 * (depth - 1)) " "

-- | The time to render a double-quoted scalar whose escaped line breaks all
