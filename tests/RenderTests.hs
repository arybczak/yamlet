-- | Rendering keeps every comment, and a second round trip gives the same
-- text. The end comments of an indentless sequence belong to its last item
-- after the round trip.
test_commentRoundTrip :: Assertion
test_commentRoundTrip = case parseDocumentsText configuration of
  Right docs -> do
    let out = renderSyntax defaultRenderOptions docs
        texts :: Document -> [T.Text]
        texts d = [t | (_, _, t) <- commentsOf d]
    case parseDocumentsText out of
      Right docs' -> do
        assertEqual ("comments\n" ++ T.unpack out) (map texts docs) (map texts docs')
        assertEqual "text" out (renderSyntax defaultRenderOptions docs')
      Left err -> assertFailure (T.unpack out ++ "\n" ++ show err)
  Left err -> assertFailure (show err)

-- | A comment without a place at its node moves to one that has it.
test_movedComments :: Assertion
test_movedComments = do
  let render :: Node -> T.Text
      render n = renderSyntax defaultRenderOptions [document n]
      withInline :: T.Text -> Node -> Node
      withInline t n = n {comments = n.comments {inline = Just t}}
      withBefore :: T.Text -> Node -> Node
      withBefore t n = n {comments = n.comments {before = [Comment t]}}
  assertEqual
    "lines above a value on the line of the key"
    "# v\na: 1\n"
    (render (mappingNode [(plainNode "a", withBefore "v" (plainNode "1"))]))
  assertEqual
    "two comments on one line"
    "# k\na: 1 # v\n"
    (render (mappingNode [(withInline "k" (plainNode "a"), withInline "v" (plainNode "1"))]))
  assertEqual
    "comment in a flow sequence"
    "a:\n- 1 # c\n- 2\n"
    (render (mappingNode [(plainNode "a", contentNode (Sequence Flow [withInline "c" (plainNode "1"), plainNode "2"]))]))
  assertEqual
    "comment on a block root"
    "--- # c\na: 1\n"
    (render (withInline "c" (mappingNode [(plainNode "a", plainNode "1")])))
  let withAfter :: T.Text -> Node -> Node
      withAfter t n = n {comments = n.comments {after = [Comment t]}}
      list :: Node -> Node
      list item =
        mappingNode
          [ (plainNode "a", withAfter "c" (sequenceNode [item]))
          , (plainNode "b", plainNode "2")
          ]
  assertEqual
    "end of an indentless list"
    "a:\n- x: 1\n  # c\nb: 2\n"
    (render (list (mappingNode [(plainNode "x", plainNode "1")])))
  assertEqual
    "end of a list with a block scalar"
    "a:\n  - |\n    x\n  # c\nb: 2\n"
    (render (list (scalarNode Literal "x\n")))

-- | Rendering a tree and parsing the result gives the same tree, except for
-- the styles, the offsets and the places of the comments. Every comment
-- stays, and rendering the result again gives the same text.
prop_roundTrip :: Tree -> Property
prop_roundTrip (Tree doc) =
  let out = renderSyntax defaultRenderOptions [doc]
  in counterexample (T.unpack out) $ case parseDocumentsText out of
       Right [doc'] ->
         conjoin
           [ counterexample "tree" $ strip doc'.root === strip (flowItems False doc.root)
           , counterexample "comments" $ L.sort (allComments doc') === L.sort (allComments doc)
           , let out' = renderSyntax defaultRenderOptions [doc']
             in counterexample ("text: " ++ firstDifference out out') (out' == out)
           ]
       r -> counterexample (show r) False
  where
    strip :: Node -> Node
    strip n =
      ( contentNode $ case n.content of
          Scalar _ t -> Scalar Plain t
          Sequence _ xs -> Sequence Block (map strip xs)
          Mapping _ kvs -> Mapping Block [(strip k, strip v) | (k, v) <- kvs]
          Alias a -> Alias a
      )
        { props = n.props
        }

    allComments :: Document -> [T.Text]
    allComments d = [t | (_, _, t) <- commentsOf d]

    -- The renderer gives an empty item of a flow sequence a tag.
    flowItems :: Bool -> Node -> Node
    flowItems inFlow n = case n.content of
      Sequence s xs ->
        let inFlow' = inFlow || (s == Flow && not (hasComments n))
        in n {content = Sequence s (map (item inFlow' . flowItems inFlow') xs)}
      Mapping s kvs ->
        let inFlow' = inFlow || (s == Flow && not (hasComments n))
        in n {content = Mapping s [(flowItems inFlow' k, flowItems inFlow' v) | (k, v) <- kvs]}
      _ -> n

    item :: Bool -> Node -> Node
    item inFlow n = case (n.props, n.content) of
      (Props Nothing NoTag, Scalar Plain "")
        | inFlow ->
            n {props = Props Nothing (Tag "tag:yaml.org,2002:null")}
      _ -> n

    -- A flow collection with comments inside becomes a block collection.
    hasComments :: Node -> Bool
    hasComments n =
      not (null [() | Comment _ <- n.comments.after]) || case n.content of
        Sequence _ xs -> any inner xs
        Mapping _ kvs -> any (\(k, v) -> inner k || inner v) kvs
        _ -> False
      where
        inner :: Node -> Bool
        inner x =
          not (null [() | Comment _ <- x.comments.before])
            || x.comments.inline /= Nothing
            || hasComments x

newtype Tree = Tree Document
  deriving stock (Show)

instance Arbitrary Tree where
  arbitrary = do
    root <- sized genNode
    c <- genComments False
    pure . Tree $ (document root) {docComments = c}

genNode :: Int -> Gen Node
genNode size = do
  n <-
    if size <= 1
      then genScalar
      else
        frequency
          [ (3, genScalar)
          , (1, contentNode . Alias <$> genAnchor)
          , (1, contentNode <$> (Sequence <$> genStyle <*> genList))
          , (1, contentNode <$> (Mapping <$> genStyle <*> genEntries))
          ]
  p <- case n.content of
    Alias _ -> pure noProps
    _ -> genProps
  c <- genComments (isCollection n)
  pure n {props = p, comments = c}
  where
    genList :: Gen [Node]
    genList = do
      k <- choose (0, 4)
      vectorOf k (genNode (size `div` 3))

    genEntries :: Gen [(Node, Node)]
    genEntries = do
      k <- choose (0, 4)
      vectorOf k ((,) <$> genNode (size `div` 4) <*> genNode (size `div` 3))

    genStyle :: Gen CollectionStyle
    genStyle = elements [Block, Flow]

    isCollection :: Node -> Bool
    isCollection n = case n.content of
      Sequence _ (_ : _) -> True
      Mapping _ (_ : _) -> True
      _ -> False

-- | Comments for a node. Only a non-empty collection has lines after it.
genComments :: Bool -> Gen Comments
genComments collection =
  frequency
    [ (3, pure noComments)
    ,
      ( 1
      , Comments
          <$> genLines
          <*> oneof [pure Nothing, Just <$> genCommentText]
          <*> (if collection then genLines else pure [])
      )
    ]
  where
    genLines :: Gen [Line]
    genLines = do
      k <- choose (0, 2)
      vectorOf k (frequency [(3, Comment <$> genCommentText), (1, pure EmptyLine)])

genCommentText :: Gen T.Text
genCommentText = elements ["a comment", "", "x", "# hash", "key: value", "- item", "'quoted'"]

genScalar :: Gen Node
genScalar = scalarNode <$> elements [minBound .. maxBound] <*> genText

genProps :: Gen Props
genProps =
  Props
    <$> oneof [pure Nothing, Just <$> genAnchor]
    <*> elements
      [ NoTag
      , NoTag
      , NonSpecificTag
      , Tag "tag:yaml.org,2002:str"
      , Tag "!local"
      , Tag "tag:example.com,2000:x"
      ]

genAnchor :: Gen T.Text
genAnchor = elements ["a", "b", "anchor"]

genText :: Gen T.Text
genText =
  oneof
    [ elements tricky
    , T.pack <$> listOf genChar
    , T.intercalate "\n" <$> listOf (T.pack <$> listOf genChar)
    ]
  where
    tricky :: [T.Text]
    tricky =
      [ ""
      , " "
      , "-"
      , "- a"
      , "? a"
      , ": a"
      , "a: b"
      , "a:b"
      , "#"
      , "a #b"
      , "true"
      , "12"
      , "---"
      , "..."
      , "foo\n"
      , "\nfoo"
      , "  lead"
      , "trail  "
      , "a\n\nb\n\n"
      , "\n"
      , "\n\n"
      , " \n"
      , "a\n "
      , "|"
      , ">"
      , "[a]"
      , "{a: b}"
      , "a, b"
      , "key:"
      , "\r\n"
      , "a\n  b\nc"
      , "  a\nb"
      , "a\n\n  b\n\nc\n"
      ]

    genChar :: Gen Char
    genChar =
      frequency
        [ (10, elements "abc xyz-:#,[]{}'\"!&*?|>%@`\\")
        , (2, elements "\t\r\x85\xA0\x2028\xFEFF\x01")
        , (1, arbitrary)
        ]

-- | The first line where two texts differ, with the line before it.
firstDifference :: T.Text -> T.Text -> String
firstDifference a b = go (1 :: Int) "" (T.lines a) (T.lines b)
  where
    go :: Int -> T.Text -> [T.Text] -> [T.Text] -> String
    go n prev xs ys = case (xs, ys) of
      (x : xs', y : ys') | x == y -> go (n + 1) x xs' ys'
      _ ->
        "line "
          ++ show n
          ++ " after "
          ++ show prev
          ++ ": "
          ++ show (take 1 xs)
          ++ " /= "
          ++ show (take 1 ys)
