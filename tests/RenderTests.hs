-- | The comments of a document with the path of their nodes.
commentsOf :: Document -> [(String, String, T.Text)]
commentsOf doc = lines_ "document" doc.docComments ++ node "" doc.root
  where
    node :: String -> Node -> [(String, String, T.Text)]
    node path n = lines_ path n.comments {after = []} ++ inner ++ lines_ path noComments {after = n.comments.after}
      where
        inner :: [(String, String, T.Text)]
        inner = case n.content of
          Sequence _ xs -> concat (zipWith (\i x -> node (path ++ "/" ++ show i) x) [0 :: Int ..] xs)
          Mapping _ kvs -> concatMap (entry path) kvs
          _ -> []

    entry :: String -> (Node, Node) -> [(String, String, T.Text)]
    entry path (k, v) =
      let path' = path ++ "/" ++ keyText k
      in node (path' ++ ":key") k ++ node path' v

    keyText :: Node -> String
    keyText k = case k.content of
      Scalar _ t -> T.unpack t
      _ -> "?"

    lines_ :: String -> Comments -> [(String, String, T.Text)]
    lines_ path c =
      [(path, "before", t) | Comment t <- c.before]
        ++ [(path, "inline", t) | Just t <- [c.inline]]
        ++ [(path, "after", t) | Comment t <- c.after]

-- | Each rule of the documentation.
test_attachment :: Assertion
test_attachment = do
  let check :: String -> [(String, String, T.Text)] -> T.Text -> Assertion
      check preface expected input = case parseDocumentsText input of
        Right [doc] -> assertEqual preface expected (commentsOf doc)
        r -> assertFailure (preface ++ ": " ++ show r)
  check "above a key" [("/b:key", "before", "c")] "a: 1\n# c\nb: 2\n"
  check "above the first key" [("", "before", "c")] "# c\na: 1\n"
  check "at the end of a value" [("/a", "inline", "c")] "a: 1 # c\n"
  check "at the end of a key" [("/a:key", "inline", "c")] "a: # c\n  b: 1\n"
  check "on a block scalar header" [("/a", "inline", "c")] "a: | # c\n  text\n"
  check "above a sequence item" [("/a/1", "before", "c")] "a:\n- 1\n# c\n- 2\n"
  check "after a flow collection" [("/a", "inline", "c")] "a: [1, 2] # c\n"
  check "on an item line" [("/0", "inline", "c")] "- # c\n  a: 1\n"
  check "at the end of an indented list" [("/a", "after", "c")] "a:\n  - 1\n  # c\nb: 2\n"
  check "at the key column after a list" [("/b:key", "before", "c")] "a:\n- 1\n# c\nb: 2\n"
  check "at the end of a nested mapping" [("/a", "after", "c")] "a:\n  b: 1\n  # c\nd: 2\n"
  check "at the end of the root" [("", "after", "c")] "a: 1\n# c\n"
  check "at the end of the document" [("document", "after", "c")] "a\n# c\n"
  check "before the marker" [("document", "before", "c")] "# c\n---\na: 1\n"
  check "on the marker line" [("document", "inline", "c")] "--- # c\na: 1\n"
  check "after the end marker" [("document", "after", "c")] "a\n...\n# c\n"
  check "on the end marker line" [("document", "after", "c")] "a\n... # c\n"
  check "inside a flow sequence" [("/0", "inline", "c"), ("/1", "before", "d")] "[a, # c\n # d\n b]\n"
  check "empty lines" [] "a: 1\n\n\nb: 2\n"
  assertEqual
    "empty line"
    (Right [EmptyLine])
    ((\case [d] | Mapping _ [_, (k, _)] <- d.root.content -> k.comments.before; _ -> []) <$> parseDocumentsText "a: 1\n\n\nb: 2\n")

