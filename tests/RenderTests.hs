-- | A scalar that the source writes on several lines keeps its lines, also
-- where the text has a space in place of a line break.
test_scalarLines :: Assertion
test_scalarLines = do
  rendersBack "folded" "options: >-\n  --health-cmd pg_isready\n  --health-interval 5s\n  --health-retries 10\n"
  rendersBack "folded with paragraphs" "a: >\n  one\n  two\n\n  three\n  four\n"
  rendersBack "folded with more indented lines" "a: >\n  one\n    two\n  three\n  four\n"
  rendersBack "folded with a space at the end of a line" "a: >-\n  one \n  two\n"
  rendersBack "empty block scalars" "a: |-\nb: >-\nc:\n- |-\n"
  rendersAs "empty block scalars with clip" "a: |-\nb: >-\n" "a: |\nb: >\n"
  rendersBack "block scalars of only line breaks" "a: |+\n\nb:\n  c: |+\n\n\n  d: 1\n"
  rendersBack "block scalar of only line breaks at the top level" "|+\n\n"
  rendersBack "plain" "a: one\n  two\n  three\n"
  rendersBack "plain with an empty line" "a: one\n\n  two\n"
  rendersBack "plain in a sequence" "- one\n  two\n"
  rendersBack "plain root" "one\n  two\n"
  rendersBack "plain in a flow sequence" "a: [one\n  two, three]\n"
  rendersBack "single-quoted" "a: 'one\n  two'\n"
  rendersBack "double-quoted" "a: \"one\n  two\"\n"
  rendersBack "double-quoted with an escaped line break" "a: \"one\\\n  two\"\n"
  rendersBack "double-quoted with an empty line" "a: \"one\n\n  two\"\n"
  rendersBack "comment after the last line" "a: one\n  two # c\n"
  rendersAs "key" "one two: a\n" "? one\n  two\n: a\n"
  rendersAs "indentation" "a: one\n  two\n" "a:   one\n      two\n"
  let folded :: String -> [T.Text] -> Assertion
      folded preface ls = do
        let out = render (mappingNode [(plainNode "a", foldedNode ls)])
        assertEqual preface ("a: >-\n" <> T.concat [if T.null l then "\n" else "  " <> l <> "\n" | l <- ls]) out
        assertEqual
          (preface ++ ", read back")
          (Right [[(foldedNode ls).content]])
          (map (\d -> [v.content | MappingContent _ kvs <- [d.root.content], (_, v) <- kvs]) <$> parseDocumentsText out)
  folded "folded node" ["one two", "three", "four"]
  folded "folded node with a space at a line start" ["one", " two", "three"]
  folded "folded node with a space at a line end" ["one ", "two"]
  folded "folded node with one line" ["one"]
  folded "folded node with empty lines" ["one", "", "two", "", "", "three"]
  folded "folded node with an indented example" ["Example:", "  GET /orders", "", "The end."]
  assertEqual
    "positions"
    (Right [ScalarLinesContent Plain "one two\nthree" [4, 8]])
    (map (\d -> d.root.content) <$> parseDocumentsText "one\n two\n\n three\n")

test_documents :: Assertion
test_documents = do
  rendersBack "markers" $
    T.unlines
      [ "first"
      , "---"
      , "second"
      , "..."
      , "%YAML 1.2"
      , "---"
      , "a: b"
      , "---"
      ]
  -- YAML 1.1 parsers need a start marker after an end marker.
  rendersAs "document after an end marker" "a\n...\n---\nb\n" "a\n...\nb\n"
  rendersAs "comment after the end marker" "a: b\n...\n# c\n---\nd: e\n" "a: b\n...\n# c\nd: e\n"
  rendersBack "comment before the directives" "a\n...\n# b\n%YAML 1.2\n---\nc\n"
  rendersBack "comments at the end of a root collection and a document" "a: 1\n# b\n\n# c\n...\n"
  rendersBack "comments around an end marker between documents" "a\n# b\n...\n# c\n---\nd\n"
  rendersAs
    "empty line before the bracket of a flow root"
    "key: value\n# zq\n...\n"
    "{\n key: value\n # zq\n\n}\n...\n"
  rendersAs
    "empty line before the bracket of a flow value"
    "a:\n  key: value\n  # zq\n\nb: 1\n"
    "a: {\n key: value\n # zq\n\n }\nb: 1\n"
  rendersAs
    "empty line before the bracket and a comment after it"
    "a: {key: value} # c\n\nb: 1\n"
    "a: {\n key: value\n\n } # c\nb: 1\n"
  assertEqual
    "comment after a byte order mark between documents"
    (Right [[("document", "after", "c")], [("document", "before", "d")]])
    (map commentsOf <$> parseDocumentsText "a: 1\n...\n\xFEFF# c\n\n\xFEFF# d\n---\nb: 2\n")
  let commented :: Document -> Document
      commented d = d {docComments = noComments {before = [Comment "c"]}}
  assertEqual
    "comment above a document without an end marker above it"
    "a\n\n# c\n---\nb\n"
    (renderSyntax defaultRenderOptions [document (plainNode "a"), commented (document (plainNode "b"))])
  assertEqual
    "comment above a document with directives"
    "a\n...\n\n# c\n%YAML 1.2\n---\nb\n"
    (renderSyntax defaultRenderOptions [document (plainNode "a"), commented (document (plainNode "b")) {version = Just (YamlVersion 1 2)}])
  let flowWithLines = (document (contentNode (SequenceContent Flow [plainNode "a"]))) {docComments = noComments {after = [Comment "c"]}}
      beforeDirectives = renderSyntax defaultRenderOptions [flowWithLines, (document (plainNode "b")) {version = Just (YamlVersion 1 2)}]
  assertEqual "lines of a flow root above directives" "[a]\n...\n# c\n%YAML 1.2\n---\nb\n" beforeDirectives
  rendersBack "lines of a flow root above directives, rendered again" beforeDirectives
  -- A block scalar without content would take the comment in.
  forM_ [Literal, Folded] $ \style ->
    assertEqual
      ("comment above a document below an empty " ++ show style ++ " root")
      "\"\"\n\n# c\n---\nb\n"
      (renderSyntax defaultRenderOptions [document (scalarNode style ""), commented (document (plainNode "b"))])
  let keyComment :: Document
      keyComment = document (mappingNode [((plainNode "k") {comments = noComments {before = [Comment "c"]}}, plainNode "v")])
      afterEnd :: T.Text
      afterEnd = renderSyntax defaultRenderOptions [(document (plainNode "a")) {explicitEnd = True}, keyComment]
      firstKeyLines :: Document -> [Line]
      firstKeyLines d = case d.root.content of
        MappingContent _ ((k, _) : _) -> k.comments.before
        _ -> []
  assertEqual "comment above the first key after an end marker" "a\n...\n---\n# c\nk: v\n" afterEnd
  assertEqual
    "comment above the first key after an end marker, read back"
    (Right [[], [Comment "c"]])
    (map firstKeyLines <$> parseDocumentsText afterEnd)
  let rootWithGap :: Bool -> Document
      rootWithGap end =
        (document (contentNode (SequenceContent Block [plainNode "a"])) {comments = noComments {after = [Comment "c", EmptyLine]}})
          { explicitEnd = end
          }
  assertEqual "empty line at the end of a block root before an end marker" "- a\n# c\n\n...\n" (renderSyntax defaultRenderOptions [rootWithGap True])
  assertEqual
    "empty line at the end of a block root before a document"
    "- a\n# c\n\n---\nb\n"
    (renderSyntax defaultRenderOptions [rootWithGap False, document (plainNode "b")])
  -- The end marker keeps the lines of a document from the next document.
  rendersBack "empty line below a flow root above an end marker" "[a]\n\n# c\n...\n---\nx\n"
  rendersBack "empty line at the end of a flow root above an end marker" "[a]\n# c\n\n...\n---\nx\n"
