  ownersRenderBack "below the indicator of an explicit value" [("/?/b:key", "before", "c")] "? a: 1\n: &x\n  # c\n  b: 2\n"
  ownersRenderBack
    "below an indicator with a comment"
    [("/1", "inline", "i"), ("/1/c:key", "before", "b")]
    "- a\n- # i\n  # b\n  c: 1\n"
  -- The renderer writes these items on the line of the indicator, with the
  -- lines above it, so the lines read back as the lines of the item.
  owners "below a bare indicator" [("/1/name:key", "before", "c")] "-\n  name: a\n-\n  # c\n  name: b\n"
  owners "below the indicator of a nested list" [("/1/0", "before", "c")] "- - a\n-\n  # c\n  - x\n"
  let withAbove :: Node -> Node
      withAbove n = n {comments = noComments {before = [Comment "a"]}}
      list :: Node
      list = sequenceNode [plainNode "1"]
  assertEqual
    "lines of a first item below its indicator"
    (Right [[("/0", "before", "a"), ("/0", "inline", "i")]])
    (map commentsOf <$> parseDocumentsText (render (sequenceNode [list {comments = noComments {before = [Comment "a"], inline = Just "i"}}])))
  let anchored :: Node -> Node
      anchored n = n {props = noProps {anchor = Just "x"}}
  assertEqual
    "lines of a first item with nested first items"
    (Right [[("/0", "before", "a")]])
    (map commentsOf <$> parseDocumentsText (render (sequenceNode [withAbove (anchored (sequenceNode [anchored list]))])))
  assertEqual "lines of a block value below its key" "k:\n# a\n\n- 1\n" (render (mappingNode [(plainNode "k", withAbove list)]))
  assertEqual
    "lines of a block value below its key read back"
    (Right [[("/k", "before", "a")]])
    (map commentsOf <$> parseDocumentsText (render (mappingNode [(plainNode "k", withAbove list)])))

-- | A comment without a place at its node moves to one that has it.
test_movedComments :: Assertion
test_movedComments = do
  let withInline :: T.Text -> Node -> Node
      withInline t n = n {comments = n.comments {inline = Just t}}
      withBefore :: T.Text -> Node -> Node
      withBefore t n = n {comments = n.comments {before = [Comment t]}}
      withAfter :: T.Text -> Node -> Node
      withAfter t n = n {comments = n.comments {after = [Comment t]}}
  assertEqual
    "lines above a value on the line of the key"
    "# v\na: 1\n"
    (render (mappingNode [(plainNode "a", withBefore "v" (plainNode "1"))]))
  assertEqual
    "lines after a scalar key"
    "# b\nk: 1\n  # a\n"
    (render (mappingNode [(withAfter "a" (withBefore "b" (plainNode "k")), plainNode "1")]))
  assertEqual
    "lines after a scalar key with a block scalar value"
    "# a\nk: |\n  text\n"
    (render (mappingNode [(withAfter "a" (plainNode "k"), contentNode (ScalarContent Literal "text\n"))]))
  assertEqual
    "lines after a block scalar value"
    "k: |\n  text\n# a\nx: 1\n"
    (render (mappingNode [(plainNode "k", withAfter "a" (contentNode (ScalarContent Literal "text\n"))), (plainNode "x", plainNode "1")]))
  assertEqual
    "lines after a list item"
    "- 1\n  # a\n- 2\n"
    (render (contentNode (SequenceContent Block [withAfter "a" (plainNode "1"), plainNode "2"])))
  assertEqual
    "empty lines at the end of an empty flow collection"
    "a: [\n  # c\n  ]\n\nb: 1\n"
    ( render
        ( mappingNode
            [ (plainNode "a", (contentNode (SequenceContent Flow [])) {comments = noComments {after = [Comment "c", EmptyLine]}})
            , (plainNode "b", plainNode "1")
            ]
        )
    )
  assertEqual
    "two comments on one line"
    "# k\na: 1 # v\n"
    (render (mappingNode [(withInline "k" (plainNode "a"), withInline "v" (plainNode "1"))]))
  assertEqual
    "comment in a flow sequence"
    "a:\n- 1 # c\n- 2\n"
    (render (mappingNode [(plainNode "a", contentNode (SequenceContent Flow [withInline "c" (plainNode "1"), plainNode "2"]))]))
  assertEqual
    "YAML 1.1 line breaks in comments"
    "# a\n# b\n# c\n# d\nk: v # e f g h\n"
    ( render
        ( mappingNode
            [(withBefore "a\x85\&b\x2028\&c\x2029\&d" (plainNode "k"), withInline "e\x85\&f\x2028\&g\x2029\&h" (plainNode "v"))]
        )
    )
  assertEqual
    "comment on a block root"
    "--- # c\na: 1\n"
    (render (withInline "c" (mappingNode [(plainNode "a", plainNode "1")])))
  rendersBack "comment on the properties of a block root" "# r\n!!map # c\n# f\na: 1\n"
  rendersBack "comment on the properties of a block root below a marker with a comment" "--- # d\n&a # c\n- x\n"
  rendersAs
    "lines below the properties of a block root with a comment"
    "# e\n\n!!map # c\n# f\na: 1\n"
    "!!map # c\n# e\n\n# f\na: 1\n"
  let rootWithLines = withBefore "r" (mappingNode [(plainNode "a", plainNode "1")])
  assertEqual "lines of a block root without an empty line" "# r\n\na: 1\n" (render rootWithLines)
  assertEqual
    "lines of a block root read back"
    (Right [[Comment "r", EmptyLine]])
    (map (\d -> d.root.comments.before) <$> parseDocumentsText (render rootWithLines))
  assertEqual
    "comment on a block root below the comment of the marker"
    "--- # d\n# c\n\na: 1\n"
    ( renderSyntax
        defaultRenderOptions
        [ (document (withInline "c" (mappingNode [(plainNode "a", plainNode "1")])))
            { docComments = noComments {inline = Just "d"}
            }
        ]
    )
  let list :: Node -> Node
      list item =
        mappingNode
          [ (plainNode "a", withAfter "c" (sequenceNode [item]))
          , (plainNode "b", plainNode "2")
          ]
  assertEqual
    "end of a list with a mapping"
    "a:\n  - x: 1\n  # c\nb: 2\n"
    (render (list (mappingNode [(plainNode "x", plainNode "1")])))
  assertEqual
    "end of a list with a block scalar"
    "a:\n  - |\n    x\n  # c\nb: 2\n"
    (render (list (scalarNode Literal "x\n")))

-- | Rendering a tree and parsing the result gives the same tree, except for
-- the styles, the offsets and the places of the comments. Every comment
-- stays, and rendering the result again gives the same text.
prop_roundTrip :: Tree -> Property
prop_roundTrip (Tree doc) =
  let out = renderSyntax defaultRenderOptions [doc]
  in counterexample (T.unpack out) $ case parseDocumentsText out of
       Right [doc'] ->
         checkCoverage . cover 10 (hasLines doc'.root) "scalars on several lines" $
           conjoin
             [ counterexample "tree" $ strip doc'.root === strip (flowItems False doc.root)
             , counterexample "comments" $ L.sort (allComments doc') === L.sort (allComments doc)
             , let out' = renderSyntax defaultRenderOptions [doc']
               in counterexample ("text: " ++ firstDifference out out') (out' == out)
             ]
       r -> counterexample (show r) False
  where
    strip :: Node -> Node
    strip n =
      ( contentNode $ case n.content of
          ScalarContent _ t -> ScalarContent Plain t
          SequenceContent _ xs -> SequenceContent Block (map strip xs)
          MappingContent _ kvs -> MappingContent Block [(strip k, strip v) | (k, v) <- kvs]
          AliasContent a -> AliasContent a
      )
        { props = n.props
        }

    -- The first line where two texts differ, with the line before it.
    firstDifference :: T.Text -> T.Text -> String
    firstDifference a b = go 1 "" (T.lines a) (T.lines b)
      where
        go :: Int -> T.Text -> [T.Text] -> [T.Text] -> String
        go n prev xs ys = case (xs, ys) of
          (x : xs', y : ys') | x == y -> go (n + 1) x xs' ys'
          _ ->
            "line "
              ++ show n
              ++ " after "
              ++ show prev
              ++ ": "
              ++ show (take 1 xs)
              ++ " /= "
              ++ show (take 1 ys)

    allComments :: Document -> [T.Text]
    allComments d = [t | (_, _, t) <- commentsOf d]

    hasLines :: Node -> Bool
    hasLines n = case n.content of
      ScalarLinesContent _ _ starts -> not (null starts)
      SequenceContent _ xs -> any hasLines xs
      MappingContent _ kvs -> any (\(k, v) -> hasLines k || hasLines v) kvs
      AliasContent _ -> False

    -- The renderer gives an empty item of a flow sequence a tag.
    flowItems :: Bool -> Node -> Node
    flowItems inFlow n = case n.content of
      SequenceContent s xs ->
        let inFlow' = inFlow || (s == Flow && not (hasComments n))
        in n {content = SequenceContent s (map (item inFlow' . flowItems inFlow') xs)}
      MappingContent s kvs ->
        let inFlow' = inFlow || (s == Flow && not (hasComments n))
        in n {content = MappingContent s [(flowItems inFlow' k, flowItems inFlow' v) | (k, v) <- kvs]}
      _ -> n

    item :: Bool -> Node -> Node
    item inFlow n = case (n.props, n.content) of
      (Props Nothing NoTag, ScalarContent Plain "")
        | inFlow ->
            n {props = Props Nothing (Tag "tag:yaml.org,2002:null")}
      _ -> n

    -- A flow collection with comments inside becomes a block collection.
    hasComments :: Node -> Bool
    hasComments n =
      not (null [() | Comment _ <- n.comments.after]) || case n.content of
        SequenceContent _ xs -> any inner xs
        MappingContent _ kvs -> any (\(k, v) -> inner k || inner v) kvs
        _ -> False
      where
        inner :: Node -> Bool
        inner x =
          not (null [() | Comment _ <- x.comments.before])
            || isJust x.comments.inline
            || hasComments x

newtype Tree = Tree Document
  deriving stock (Show)

instance Arbitrary Tree where
  arbitrary = do
    root <- sized genNode
    c <- genComments False
    pure . Tree $ (document root) {docComments = c}

genNode :: Int -> Gen Node
genNode size = do
  n <-
    if size <= 1
      then genScalar
      else
        frequency
          [ (3, genScalar)
          , (1, contentNode . AliasContent <$> genAnchor)
          , (1, contentNode <$> (SequenceContent <$> genStyle <*> genList))
          , (1, contentNode <$> (MappingContent <$> genStyle <*> genEntries))
          ]
  p <- case n.content of
    AliasContent _ -> pure noProps
    _ -> genProps
  c <- genComments (isCollection n)
  pure n {props = p, comments = c}
  where
    genList :: Gen [Node]
    genList = do
      k <- choose (0, 4)
      vectorOf k (genNode (size `div` 3))

    genEntries :: Gen [(Node, Node)]
    genEntries = do
      k <- choose (0, 4)
      vectorOf k ((,) <$> genNode (size `div` 4) <*> genNode (size `div` 3))

    genStyle :: Gen CollectionStyle
    genStyle = elements [Block, Flow]

    isCollection :: Node -> Bool
    isCollection n = case n.content of
      SequenceContent _ (_ : _) -> True
      MappingContent _ (_ : _) -> True
      _ -> False

    -- A scalar, often with positions of new lines. Some positions are not
    -- valid, e.g. outside the text or twice the same.
    genScalar :: Gen Node
    genScalar = do
      style <- elements [minBound .. maxBound]
      t <- genText
      starts <- frequency [(1, pure []), (2, L.sort <$> listOf (choose (0, T.length t + 1)))]
      pure (contentNode (ScalarLinesContent style t starts))

    genProps :: Gen Props
    genProps =
      Props
        <$> oneof [pure Nothing, Just <$> genAnchor]
        <*> elements
          [ NoTag
          , NoTag
          , NonSpecificTag
          , Tag "tag:yaml.org,2002:str"
          , Tag "!local"
          , Tag "tag:example.com,2000:x"
          ]

    genAnchor :: Gen T.Text
    genAnchor = elements ["a", "b", "anchor"]

    genText :: Gen T.Text
    genText =
      oneof
        [ elements tricky
        , T.pack <$> listOf genChar
        , T.intercalate "\n" <$> listOf (T.pack <$> listOf genChar)
        ]
      where
        tricky :: [T.Text]
        tricky =
          [ ""
          , " "
          , "-"
          , "- a"
          , "? a"
          , ": a"
          , "a: b"
          , "a:b"
          , "#"
          , "a #b"
          , "true"
          , "12"
          , "---"
          , "..."
          , "foo\n"
          , "\nfoo"
          , "  lead"
          , "trail  "
          , "a\n\nb\n\n"
          , "\n"
          , "\n\n"
          , " \n"
          , "a\n "
          , "|"
          , ">"
          , "[a]"
          , "{a: b}"
          , "a, b"
          , "key:"
          , "\r\n"
          , "a\n  b\nc"
          , "  a\nb"
          , "a\n\n  b\n\nc\n"
          ]

        genChar :: Gen Char
        genChar =
          frequency
            [ (10, elements "abc xyz-:#,[]{}'\"!&*?|>%@`\\")
            , (2, elements "\t\r\x85\xA0\x2028\xFEFF\x01")
            , (1, arbitrary)
            ]

-- | Comments for a node. Only a non-empty collection has lines after it.
genComments :: Bool -> Gen Comments
genComments collection =
  frequency
    [ (3, pure noComments)
    ,
      ( 1
      , Comments
          <$> genLines
          <*> oneof [pure Nothing, Just <$> genCommentText]
          <*> (if collection then genLines else pure [])
      )
    ]
  where
    genLines :: Gen [Line]
    genLines = do
      k <- choose (0, 2)
      vectorOf k (frequency [(3, CommentLine <$> elements [1, 1, 2, 3] <*> genCommentText), (1, pure EmptyLine)])

    genCommentText :: Gen T.Text
    genCommentText = elements ["a comment", "", "x", "# hash", "key: value", "- item", "'quoted'"]
